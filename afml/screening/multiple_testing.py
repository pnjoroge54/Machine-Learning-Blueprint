"""
Multiple-testing corrections for feature screening.

Screening ``K`` candidate features is the same statistical problem Masters
diagnoses for strategy selection: the best of many draws is not the best draw,
it is the luckiest. Measured on the reference configuration, the best of fifty
genuinely useless features has null normalized MI of 0.0150 against a
single-feature null mean of 0.0108. The winner's curse does not care whether a
model was fitted.

Four corrections are provided. The one to use is
:func:`westfall_young_maxt`, and the reason is dependence.

Bonferroni and Holm control the family-wise error rate under any dependence
structure, but they pay for that generality by assuming the worst case. Features
in the Blueprint pipeline are heavily correlated: fractionally differenced price
at neighboring ``d``, several volatility estimators, a family of session dummies.
The effective number of independent tests is far below ``K``, so Holm discards
real signal.

Benjamini-Hochberg controls the false discovery rate but requires independence or
positive regression dependence. Benjamini-Yekutieli removes that assumption at
the cost of a ``log K`` penalty.

Westfall-Young sidesteps the question. Because the null is generated by
permutation anyway, the same permutation can be applied to every feature at once,
which preserves the empirical correlation structure among them. The maximum
statistic across features under that joint null is then the exact reference
distribution for the largest observed statistic. No dependence assumption is
made, and no worst case is assumed either.

The requirement this imposes on callers is architectural rather than
statistical: features must be screened jointly, with one shared permutation per
replicate, not one at a time. :func:`afml.screening.mutual_information.mi_screen`
is built that way.

References
----------
Westfall, P. H., & Young, S. S. (1993). *Resampling-Based Multiple Testing.*
Holm, S. (1979). A simple sequentially rejective multiple test procedure.
Benjamini, Y., & Hochberg, Y. (1995). Controlling the false discovery rate.
Benjamini, Y., & Yekutieli, D. (2001). The control of the false discovery rate
under dependency.
"""

from __future__ import annotations

import numpy as np

__all__ = [
    "benjamini_hochberg",
    "benjamini_yekutieli",
    "bonferroni",
    "effective_number_of_tests",
    "holm_bonferroni",
    "westfall_young_maxt",
]


def _as_p(p_values) -> np.ndarray:
    p = np.asarray(p_values, dtype=float)
    if p.ndim != 1:
        raise ValueError("p_values must be one-dimensional")
    if np.any((p <= 0.0) | (p > 1.0)):
        raise ValueError("p-values must lie in (0, 1]; use the add-one permutation p-value")
    return p


def bonferroni(p_values) -> np.ndarray:
    """Single-step family-wise correction. Included as a baseline.

    :param p_values: (array) Raw p-values.
    :return: (np.ndarray) Adjusted p-values, clipped at 1.
    """
    p = _as_p(p_values)
    return np.minimum(1.0, p * p.size)


def holm_bonferroni(p_values) -> np.ndarray:
    """Step-down family-wise correction. Uniformly more powerful than Bonferroni.

    :param p_values: (array) Raw p-values.
    :return: (np.ndarray) Adjusted p-values in the input order.
    """
    p = _as_p(p_values)
    k = p.size
    order = np.argsort(p)
    adjusted = np.maximum.accumulate((k - np.arange(k)) * p[order])
    out = np.empty(k, dtype=float)
    out[order] = np.minimum(1.0, adjusted)
    return out


def benjamini_hochberg(p_values) -> np.ndarray:
    """False-discovery-rate control under independence or positive dependence.

    :param p_values: (array) Raw p-values.
    :return: (np.ndarray) Adjusted p-values in the input order.
    """
    p = _as_p(p_values)
    k = p.size
    order = np.argsort(p)
    ranked = p[order] * k / (np.arange(k) + 1)
    adjusted = np.minimum.accumulate(ranked[::-1])[::-1]
    out = np.empty(k, dtype=float)
    out[order] = np.minimum(1.0, adjusted)
    return out


def benjamini_yekutieli(p_values) -> np.ndarray:
    """False-discovery-rate control under arbitrary dependence.

    Applies the harmonic penalty ``sum(1/i)`` for ``i`` in ``1..K``, which grows
    like ``log K``. Correct but conservative; prefer
    :func:`westfall_young_maxt` when a permutation null is available.

    :param p_values: (array) Raw p-values.
    :return: (np.ndarray) Adjusted p-values in the input order.
    """
    p = _as_p(p_values)
    penalty = np.sum(1.0 / np.arange(1, p.size + 1))
    return np.minimum(1.0, benjamini_hochberg(p) * penalty)


def westfall_young_maxt(observed, null_matrix) -> np.ndarray:
    """Permutation-based family-wise correction via the maximum statistic.

    For each permutation replicate the maximum statistic across all features is
    recorded. The adjusted p-value for feature ``j`` is the fraction of
    replicates whose maximum equals or exceeds the observed statistic for ``j``.
    Because every feature is evaluated under the same permutation, the joint null
    inherits the empirical correlation among features, and no dependence
    assumption is required.

    :param observed: (array) Observed statistics, one per feature, length ``K``.
    :param null_matrix: (np.ndarray) Shape ``(B, K)``. Row ``b`` holds the
        statistic for every feature under permutation ``b``. Rows must correspond
        to shared permutations; independently permuting each feature destroys the
        dependence structure this correction exists to exploit.
    :return: (np.ndarray) Adjusted p-values, length ``K``.

    .. note:: Single-step, not step-down. Step-down Westfall-Young is more
       powerful but requires subset pivotality and a nested maximum over
       progressively smaller feature sets. The single-step version is valid under
       weaker conditions and is what a screening gate should use, since the cost
       of a false negative here is a discarded feature rather than a deployed one.
    """
    observed = np.asarray(observed, dtype=float)
    null_matrix = np.asarray(null_matrix, dtype=float)
    if null_matrix.ndim != 2:
        raise ValueError("null_matrix must be two-dimensional, shape (B, K)")
    if null_matrix.shape[1] != observed.size:
        raise ValueError(
            f"null_matrix has {null_matrix.shape[1]} feature columns but "
            f"{observed.size} observed statistics were supplied"
        )

    null_max = np.nanmax(null_matrix, axis=1)
    n_perm = null_max.size
    counts = np.array([np.sum(null_max >= obs) for obs in observed], dtype=float)
    return (1.0 + counts) / (1.0 + n_perm)


def effective_number_of_tests(null_matrix) -> float:
    """Number of independent tests the correlated family behaves like.

    Compares the observed maximum-statistic null against the maximum of ``M``
    independent draws from the marginal null, and solves for ``M``. Reported as a
    diagnostic: a family of eighty correlated features that behaves like twelve
    independent ones tells you how much power Holm was discarding.

    :param null_matrix: (np.ndarray) Shape ``(B, K)`` joint permutation null.
    :return: (float) Effective test count in ``[1, K]``.
    """
    null_matrix = np.asarray(null_matrix, dtype=float)
    _, k = null_matrix.shape
    pooled = null_matrix.ravel()
    pooled = pooled[np.isfinite(pooled)]
    if pooled.size == 0:
        return 1.0

    observed_max_mean = float(np.nanmean(np.nanmax(null_matrix, axis=1)))

    # Expected maximum of m i.i.d. draws from the pooled marginal, by quantile.
    def expected_max(m: float) -> float:
        return float(np.quantile(pooled, np.clip(1.0 - 1.0 / (m + 1.0), 0.0, 1.0)))

    lo, hi = 1.0, float(k)
    for _ in range(40):
        mid = (lo + hi) / 2.0
        if expected_max(mid) < observed_max_mean:
            lo = mid
        else:
            hi = mid
    return float(np.clip((lo + hi) / 2.0, 1.0, k))
